package shell

import "fmt"

func RenderHook(sourcePath, binaryName string) string {
	return fmt.Sprintf(`# generated by allyas 
if [ -f %q ]; then
	. %q
fi

allyas() {
	command %s "$@"
	status=$?

	if [ $status -eq 0 ]; then
		case "$1" in
			create|edit|remove|init)
				if [ -f %q ]; then
					. %q
				fi
				;;
		esac
	fi
	
return $status
}
		`, sourcePath, sourcePath, binaryName, sourcePath, sourcePath)
}
